# Return a list of campaigns:
@app.get("/campaigns")
async def read_campaigns():
    return {"campaigns": data}


# Return a single campaign by ID:
@app.get("/campaigns/{campaign_id}")
async def read_campaign(campaign_id: int):
    for campaign in data:
        if campaign["campaign_id"] == campaign_id:
            return {"campaign": campaign}
    return {"error": "Campaign not found"}, 404


# Create a new campaign:
@app.post("/campaigns")
async def create_campaign(body: dict[str, Any]):
    new_campaign_id = max(c["campaign_id"] for c in data) + 1
    campaign = {
        "campaign_id": new_campaign_id,
        "name": body.get("name"),
        "due_date": body.get("due_date"),
        "created_at": datetime.now().isoformat(),
    }
    data.append(campaign)
    return {"message": "Campaign created", "campaign": campaign}, 201


# Update an existing campaign:
@app.put("/campaigns/{campaign_id}")
async def update_campaign(campaign_id: int, body: dict[str, Any]):
    for campaign in data:
        if campaign["campaign_id"] == campaign_id:
            campaign["name"] = body.get("name", campaign["name"])
            campaign["due_date"] = body.get("due_date", campaign["due_date"])
            campaign["created_at"] = campaign.get("created_at", campaign["created_at"])
            return {"message": "Campaign updated", "campaign": campaign}
    return {"error": "Campaign not found"}, 404


# Delete a campaign:
@app.delete("/campaigns/{campaign_id}")
async def delete_campaign(campaign_id: int):
    for i, campaign in enumerate(data):
        if campaign["campaign_id"] == campaign_id:
            data.pop(i)
            return {"message": "Campaign deleted"}
    return {"error": "Campaign not found"}, 404
